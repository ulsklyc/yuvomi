test('encodeEnvValue quotet Werte mit Whitespace/# und escaped Quotes/Backslash', () => {
  assert.equal(encodeEnvValue('pass word'), '"pass word"');
  assert.equal(encodeEnvValue(' leading'), '" leading"');
  assert.equal(encodeEnvValue('a # b'), '"a # b"');
  assert.equal(encodeEnvValue('say "hi"'), '"say \\"hi\\""');
  assert.equal(encodeEnvValue('back\\slash'), '"back\\\\slash"');
});

test('encodeEnvValue verdoppelt $ zum Compose-Literal ($ -> $$)', () => {
  // Ohne Quoting-Bedarf: nur $ verdoppelt.
  assert.equal(encodeEnvValue('p$w0rd'), 'p$$w0rd');
  // Mit Quoting-Bedarf (Space): gequotet UND $ verdoppelt.
  assert.equal(encodeEnvValue('p$ w'), '"p$$ w"');
});

